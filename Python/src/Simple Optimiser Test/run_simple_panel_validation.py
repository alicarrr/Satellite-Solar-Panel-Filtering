def main():
    if solve_new_filter:
        # Solve and save the complete set of results and plotting inputs.
        payload = solve_validation()
        results_file.parent.mkdir(parents=True, exist_ok=True)
        with results_file.open("wb") as stream:
            pickle.dump(payload, stream)
        print(f"Saved {results_file}")
    else:
        # The regenerated pickle already contains everything needed to plot.
        with results_file.open("rb") as stream:
            payload = pickle.load(stream)
        print(f"Loaded {results_file}")

    print_results(payload)
    if make_plots:
        plot_validation(payload)


if __name__ == "__main__":
    main()
