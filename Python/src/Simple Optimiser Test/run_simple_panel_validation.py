# Independent calculations used to check the optimiser.
def blackbody_band_power(temperature):
    """Return blackbody power per unit area in each bin, in W/m^2."""
    # Wavelengths are rows and temperatures are columns. Convert nm to metres
    # before applying Planck's law, then multiply by the width of each bin.
    wavelength_m = panel.wavelength_nm[:, None] * nm
    bandwidth_m = panel.bandwidth_nm[:, None] * nm
    temperature = np.atleast_1d(temperature)[None, :]
    exponent = h * c / (wavelength_m * k * temperature)

    # expm1(x) evaluates exp(x) - 1 accurately when x is small.
    return (2 * np.pi * h * c**2 * bandwidth_m / (wavelength_m**5 * np.expm1(exponent)))


def check_solution(filters, temperature, weights, solver_cost=None, slope_limits=False):
    """Recalculate the optical response, cost and temperatures, then check them."""
    alpha = np.asarray(filters["alpha"])
    rho = np.asarray(filters["rho"])
    tau = np.asarray(filters["tau"])

    # Repeated reflections determine how much light reaches the panel and
    # how much is absorbed or reflected by the complete filter-panel system.
    illumination = tau / (1 - rho * panel.panel_reflectivity)
    system_alpha = (alpha * (1 + panel.panel_reflectivity * illumination) + panel.panel_absorptivity * illumination)
    system_rho = rho + tau * panel.panel_reflectivity * illumination

    # Incident inputs are already watts per bin, so these sums need no
    # additional wavelength width. Electrical output is removed from heating.
    electrical_power = np.dot(panel.incident_power_w, illumination * panel.electrical_conversion)
    absorbed_power = np.dot(panel.incident_power_w, system_alpha)
    emitted_power = panel.area_m2 * (system_alpha @ blackbody_band_power(temperature))
    thermal_capacity = panel.mass_kg * panel.heat_capacity_j_per_kg_k

    heating_power = absorbed_power - electrical_power

    # At each Euler interval, stored energy must equal net heat input.
    balance_error = (thermal_capacity * np.diff(temperature) - (heating_power - emitted_power[:-1]) * panel.interval_s[:-1])

    # Independently replay the same filter from the initial temperature.
    replay = np.empty_like(temperature)
    replay[0] = panel.initial_temperature_k
    for index in range(temperature.size - 1):
        emission = panel.area_m2 * np.dot(system_alpha, blackbody_band_power(replay[index])[:, 0])
        replay[index + 1] = replay[index] + (panel.interval_s[index] * (heating_power - emission) / thermal_capacity)

    # Reproduce the three objective terms using this case's own weights.
    duration = np.sum(panel.interval_s)
    useful_energy = electrical_power * duration
    incident_energy = np.sum(panel.incident_power_w) * duration
    tracking_error = temperature - panel.target_temperature_k
    tracking = np.mean((tracking_error / panel.temperature_reference_k)**2)
    roughness = sum(
        np.sum(np.diff(coefficient)**2) for coefficient in (alpha, rho, tau)
    ) / alpha.size
    weight_energy, weight_temperature, weight_smoothness = weights
    cost = (-weight_energy * useful_energy / incident_energy+ weight_temperature * tracking+ weight_smoothness * roughness
    )

    # Optical conservation, coefficient bounds and temperature limits.
    assert np.allclose(alpha + rho + tau, 1, atol=1e-7, rtol=0), "Filter conservation failed"
    assert np.allclose(system_alpha + system_rho, 1, atol=1e-7, rtol=0), "System conservation failed"
    for coefficient in (alpha, rho, tau):
        assert np.min(coefficient) >= -1e-7, "Negative filter coefficient"
        assert np.max(coefficient) <= 1 + 1e-7, "Filter coefficient exceeds one"
    assert np.min(temperature) >= panel.temperature_min_k - 1e-7
    assert np.max(temperature) <= panel.temperature_max_k + 1e-7
    assert abs(temperature[0] - panel.initial_temperature_k) < 1e-7

    # Energy residuals are in joules and replay differences are in kelvin.
    assert np.max(np.abs(balance_error)) < 1e-5, "Thermal balance failed"
    assert np.max(np.abs(replay - temperature)) < 1e-5, "Temperature replay failed"
    if solver_cost is not None:
        assert abs(cost - solver_cost) < 1e-7, "Independent cost check failed"

    # Adjacent spectral coefficients must satisfy both enabled slope limits.
    if slope_limits:
        allowed_step = np.minimum(slope_per_nm * np.diff(panel.wavelength_nm), slope_per_log_wavelength * np.diff(np.log(panel.wavelength_nm)))
        for coefficient in (alpha, rho, tau):
            assert np.all(np.abs(np.diff(coefficient)) <= allowed_step + 1e-7)

    return {
        "filters": filters,
        "temperature": temperature,
        "power": electrical_power,
        "absorbed": absorbed_power,
        "emitted": emitted_power,
        "energy": useful_energy,
        "cost": cost,
        "rmse": np.sqrt(np.mean(tracking_error**2)),
        "max_error": np.max(np.abs(tracking_error)),
        "balance_error": np.max(np.abs(balance_error)),
        "replay_error": np.max(np.abs(replay - temperature)),
        "optics_error": np.max(np.abs(alpha + rho + tau - 1)),
        "system_alpha": system_alpha,
    }


# Set up the test panel, solve the three cases and check the results.
def solve_validation():
    """Run the existing optimiser with the simple panel inputs."""
    optimiser.t_set = panel.target_temperature_k
    optimiser.t_ref_scale = panel.temperature_reference_k
    optimiser.t_min = panel.temperature_min_k
    optimiser.t_max = panel.temperature_max_k
    optimiser.w_elec = 1.0
    optimiser.internal_heat_load_w = 0.0

    # The optimiser expects power shaped as [panel, time, wavelength].
    # Repeat this single panel's constant spectrum at every time sample.
    bin_count = panel.wavelength_nm.size
    incident = np.broadcast_to(
        panel.incident_power_w, (1, panel.time_s.size, bin_count)
    ).copy()
    data = optimiser.SimData(
        lam_nm=panel.wavelength_nm,
        dlam_nm=panel.bandwidth_nm,
        lam_edges_nm=panel.wavelength_edges_nm,
        t=panel.time_s,
        dt=panel.interval_s,
        q_in=incident,
        material=np.array([0]),
        labels=["panel"],
        mass=np.array([panel.mass_kg]),
        heat_cap=np.array([panel.heat_capacity_j_per_kg_k]),
        area=np.array([panel.area_m2]),
        T0=np.array([panel.initial_temperature_k]),
        native_lam_nm=panel.wavelength_nm,
        native_idx=np.arange(bin_count),
        native_q_spectrum=panel.incident_power_w * np.sum(panel.interval_s))

    # Supply the wafer properties at five temperatures. Every row is the
    # same, so the existing interpolation returns constant conversion.
    temperature_grid = np.linspace(
        panel.temperature_min_k, panel.temperature_max_k, 5
    )
    lookup = {
        "temperature_C": temperature_grid - 273.15,
        "wavelength_nm": panel.wavelength_nm,
        "total_absorptivity": np.tile(panel.wafer_absorptivity, (5, 1)),
        "reflectivity": np.tile(panel.wafer_reflectivity, (5, 1)),
        "transmissivity": np.tile(panel.wafer_transmissivity, (5, 1)),
        "electrical_absorptivity_mpp": np.tile(panel.electrical_conversion, (5, 1)),
        "valid_optics_mask": np.ones(bin_count, dtype=bool),
    }

    # Temporarily give the existing property builder this test lookup instead
    # of reading a silicon data file. It still performs the backing calculation.
    def load_test_lookup():
        return lookup

    original_loader = optimiser.load_spectral_lookup
    optimiser.panel_spectral_source = {0: "lookup"}
    optimiser.lookup_material = 0
    try:
        optimiser.load_spectral_lookup = load_test_lookup
        backed = optimiser.build_panel_properties(data, verbose=False)
    finally:
        optimiser.load_spectral_lookup = original_loader

    # For case 3, prescribe the expected opaque panel directly. Its conversion
    # function returns the same array for every temperature.
    def fixed_conversion(temperature):
        return panel.electrical_conversion

    opaque = optimiser.PanelProperties(
        alpha_abs={0: panel.panel_absorptivity},
        eps_emit={0: panel.panel_absorptivity},
        rho_abs={0: panel.panel_reflectivity},
        rho_emit={0: panel.panel_reflectivity},
        alpha_elec={0: fixed_conversion},
        source={0: "opaque equivalent"},
        t_bounds=(panel.temperature_min_k, panel.temperature_max_k),
        lookup_info={})

    # Check the property builder and interpolation before optimisation.
    for field in ("alpha_abs", "eps_emit", "rho_abs", "rho_emit"):
        assert np.allclose(getattr(backed, field)[0], getattr(opaque, field)[0], atol=1e-12, rtol=0)
    for temperature in np.linspace(panel.temperature_min_k, panel.temperature_max_k, 9):
        conversion = np.asarray(backed.alpha_elec[0](temperature)).ravel()
        assert np.allclose(conversion, panel.electrical_conversion, atol=1e-12, rtol=0)

    # Both panel descriptions must give the same unfiltered response.
    baseline_t, baseline_power = optimiser.simulate_unfiltered(data, backed)
    opaque_t, opaque_power = optimiser.simulate_unfiltered(data, opaque)
    assert np.allclose(baseline_t, opaque_t, atol=1e-9, rtol=0)
    assert np.allclose(baseline_power, opaque_power, atol=1e-11, rtol=0)

    # Recover wafer heating plus backing heating from the first Euler update.
    wafer_heat = np.dot(panel.incident_power_w, panel.wafer_thermal_absorptivity)
    backing_heat = np.dot(panel.incident_power_w, panel.wafer_transmissivity)
    initial_emission = panel.area_m2 * np.dot(
        panel.panel_absorptivity, blackbody_band_power(panel.initial_temperature_k)[:, 0]
    )
    thermal_capacity = panel.mass_kg * panel.heat_capacity_j_per_kg_k
    recovered_heat = (
        thermal_capacity * (baseline_t[0, 1] - baseline_t[0, 0]) / panel.interval_s[0]
        + initial_emission
    )
    assert backing_heat > 0
    assert abs(recovered_heat - wafer_heat - backing_heat) < 1e-10

    # Each row gives the case name, panel properties and temperature/smoothing
    # weights. Electrical energy has weight one in all three cases.
    case_settings = (
        ("energy_only", backed, 0.0, 0.0),
        ("combined", backed, temperature_weight, smoothness_weight),
        ("opaque_equivalent", opaque, temperature_weight, smoothness_weight))
    cases = {}
    case_payloads = {}
    for name, properties, weight_temperature, weight_smoothness in case_settings:
        optimiser.w_temp = weight_temperature
        optimiser.w_smooth = weight_smoothness
        use_slopes = name != "energy_only"

        # Energy-only has no slope limits. Both combined cases use both limits.
        optimiser.d_smooth = None
        optimiser.d_smooth_log = None
        if use_slopes:
            optimiser.d_smooth = {0: {key: slope_per_nm for key in ("alpha", "rho", "tau")}}
            optimiser.d_smooth_log = {0: {key: slope_per_log_wavelength for key in ("alpha", "rho", "tau")}}

        print(f"\n{name}", flush=True)
        problem = optimiser.build_problem(data, properties, verbose=False, solver_options=optimiser.ipopt_options_quiet.copy())
        best, trials = optimiser.multi_start(problem, starts=starts, seed=random_seed)
        weights = (1.0, weight_temperature, weight_smoothness)

        # Check every converged start, then retain the best solution.
        successful_costs = []
        for trial in trials:
            if trial.success:
                check_solution(trial.filters[0], trial.temperature["panel"], weights, trial.J, use_slopes)
                successful_costs.append(trial.J)
        cases[name] = check_solution(best.filters[0], best.temperature["panel"], weights, best.J, use_slopes)
        cases[name]["successful_starts"] = len(successful_costs)
        cases[name]["attempted_starts"] = len(trials)
        cases[name]["cost_spread"] = np.ptp(successful_costs)

        # Preserve the normal optimiser payload for each case.
        case_payloads[name] = optimiser.solution_payload(best, trials, problem, properties)
        case_payloads[name]["model_assumptions"]["electrical"] = ("Temperature-independent electrical step from simple_panel_properties.py")
        case_payloads[name]["settings"]["n_filter_bands"] = bin_count
        case_payloads[name]["settings"]["band_spacing"] = "piecewise logarithmic"

    # A transparent filter gives the unfiltered reference and energy bound.
    clear_filter = {
        "alpha": np.zeros(bin_count),
        "rho": np.zeros(bin_count),
        "tau": np.ones(bin_count),
    }
    baseline = check_solution(
        clear_filter, baseline_t[0],
        (1.0, temperature_weight, smoothness_weight))
    combined = cases["combined"]
    equivalent = cases["opaque_equivalent"]
    energy_bound = (np.dot(panel.incident_power_w, panel.electrical_conversion) * np.sum(panel.interval_s))
    assert abs(cases["energy_only"]["energy"] - energy_bound) < 1e-3
    assert abs(combined["energy"] - energy_bound) < 1e-3
    assert combined["max_error"] < 1e-3
    assert abs(combined["energy"] - equivalent["energy"]) < 1e-3
    assert abs(combined["cost"] - equivalent["cost"]) < 1e-7
    assert np.max(np.abs(combined["temperature"] - equivalent["temperature"])) < 1e-3

    # Hold the best filter fixed and compare the optimiser's emission routine
    # with the independent Planck calculation at three temperatures.
    temperatures = panel.target_temperature_k + np.array([-10, 0, 10])
    emission = []
    for temperature in temperatures:
        band_power = optimiser.planck_band_power(float(temperature), panel.wavelength_nm, panel.bandwidth_nm)
        emitted_power = panel.area_m2 * np.dot(combined["system_alpha"], np.asarray(band_power).ravel())
        emission.append(emitted_power)
    emission = np.array(emission)
    independent_emission = panel.area_m2 * (combined["system_alpha"] @ blackbody_band_power(temperatures))
    assert np.allclose(emission, independent_emission, atol=1e-10, rtol=0)
    assert emission[2] > emission[1] > emission[0]
    assert emission[2] - 2 * emission[1] + emission[0] > 0
    print("All checks passed.")

    # Start with the standard combined-result payload. Store all validation
    # cases and plot inputs so later plotting needs only this pickle.
    payload = case_payloads["combined"].copy()
    payload["validation_payloads"] = case_payloads
    payload["validation_cases"] = cases
    payload["validation_unfiltered"] = baseline
    payload["validation_backing"] = (wafer_heat, backing_heat, recovered_heat)
    payload["validation_emission"] = {"temperature": temperatures, "power": emission}
    payload["validation_incident_power_w"] = panel.incident_power_w.copy()
    payload["validation_spectral_regions"] = list(panel.spectral_regions)
    payload["validation_properties"] = {
        name: getattr(panel, name) for name in ("wavelength_edges_nm", "wafer_absorptivity", "wafer_reflectivity","wafer_transmissivity", "electrical_conversion", "wafer_thermal_absorptivity","panel_absorptivity", "panel_reflectivity", "panel_transmissivity")
    }
    return payload


def print_results(payload):
    """Print the stored performance and verification results."""
    cases = payload["validation_cases"]
    baseline = payload["validation_unfiltered"]
    combined = cases["combined"]
    wafer_heat, backing_heat, total_heat = payload["validation_backing"]
    print(
        f"\nBacking heating: {wafer_heat:.2f} W wafer"
        f" + {backing_heat:.2f} W backing = {total_heat:.2f} W total"
    )

    print("\nFixed-filter emission:")
    temperatures = payload["validation_emission"]["temperature"]
    powers = payload["validation_emission"]["power"]
    for temperature, power in zip(temperatures, powers):
        print(f"  {temperature:.2f} K: {power:.6f} W")

    # Costs use each case's own weights, so the energy-only cost excludes tracking.
    print("\nPerformance (costs use each case's own objective weights):")
    print(
        f"{'Case':<20} {'Energy (J)':>12} {'Final T (K)':>13}"
        f" {'RMSE (K)':>13} {'Cost':>13}"
    )
    for name, result in [("unfiltered", baseline)] + list(cases.items()):
        print(
            f"{name:<20} {result['energy']:12.6f}"
            f" {result['temperature'][-1]:13.6f}"
            f" {result['rmse']:13.6g} {result['cost']:13.8f}"
        )
    print(f"Maximum target error: {combined['max_error']:.3e} K")
    print(f"Energy-balance residual: {combined['balance_error']:.3e} J")
    print(f"Temperature replay error: {combined['replay_error']:.3e} K")
    print(f"Optical conservation error: {combined['optics_error']:.3e}")
    for name, result in cases.items():
        print(
            f"{name}: {result['successful_starts']}/{result['attempted_starts']}"
            f" starts converged, cost spread {result['cost_spread']:.3e}"
        )


